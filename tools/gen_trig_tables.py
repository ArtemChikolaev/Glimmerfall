#!/usr/bin/env python3
"""Генерирует sim/Numerics/TrigTables.g.cs — таблицы синуса и арктангенса для сима.

Сим не вызывает libm (правило детерминизма, ADR 0002): таблицы считаются здесь один раз в double
и коммитятся целыми литералами. Тест sim.tests/TrigTableTests пересчитывает их и сверяет бит-в-бит.
Запуск: python3 tools/gen_trig_tables.py
"""
import math
from pathlib import Path

STEPS = 1024  # шагов на четверть оборота (синус) и на октант (арктангенс)
ONE = 1 << 16  # Q16.16
FULL_TURN = 1 << 16  # единиц угла на оборот


def rounded(x: float) -> int:
    return math.floor(x + 0.5)


def sin_quarter() -> list[int]:
    return [rounded(math.sin(i * (math.pi / 2) / STEPS) * ONE) for i in range(STEPS + 1)]


def atan_octant() -> list[int]:
    return [rounded(math.atan(i / STEPS) * FULL_TURN / (2 * math.pi)) for i in range(STEPS + 1)]


def emit(name: str, values: list[int], doc: str) -> str:
    rows = []
    for i in range(0, len(values), 16):
        rows.append("            " + ", ".join(str(v) for v in values[i:i + 16]) + ",")
    body = "\n".join(rows)
    return f"        /// <summary>{doc}</summary>\n        internal static readonly int[] {name} =\n        {{\n{body}\n        }};\n"


def main() -> None:
    out = Path(__file__).resolve().parent.parent / "sim" / "Numerics" / "TrigTables.g.cs"
    text = (
        "// <auto-generated>\n"
        "// Сгенерировано tools/gen_trig_tables.py — не править руками; тест TrigTableTests сверяет таблицы.\n"
        "// </auto-generated>\n"
        "namespace Glimmerfall.Sim.Numerics\n"
        "{\n"
        "    internal static class TrigTables\n"
        "    {\n"
        f"        internal const int Steps = {STEPS};\n\n"
        + emit("SinQuarter", sin_quarter(), "sin(i·(π/2)/Steps) в Q16.16, i = 0..Steps.")
        + "\n"
        + emit("AtanOctant", atan_octant(), "atan(i/Steps) в единицах угла (65536 на оборот), i = 0..Steps.")
        + "    }\n"
        "}\n"
    )
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
